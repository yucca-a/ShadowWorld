-- Run only in the copied, disposable FrostArt test world.
AddSimPostInit(function()
    if not TheWorld.ismastersim then return end
    assert(TheNet:GetServerName() == "ShadowWorld disposable frost art check")
    TheWorld:DoStaticTaskInTime(2, function()
        local shrine = assert(SpawnPrefab("frostshrine2hm"))
        -- Synthetic server-only players have no connected clients to keep the
        -- test region awake. Keep this disposable fixture ticking explicitly.
        shrine.entity:SetCanSleep(false)
        local first, second = assert(SpawnPrefab("wilson")), assert(SpawnPrefab("wilson"))
        for _, player in ipairs({first, second}) do
            if not table.contains(AllPlayers, player) then table.insert(AllPlayers, player) end
        end
        shrine.Transform:SetPosition(0, 0, 0)
        first.Transform:SetPosition(1, 0, 0)
        second.Transform:SetPosition(15, 0, 0)
        TheWorld:DoStaticTaskInTime(1, function()
            local prox = assert(shrine.components.playerprox)
            assert(shrine.components.prototyper == nil, "existing recipes must stay unchanged")
            assert(prox.near == TUNING.RESEARCH_MACHINE_DIST)
            prox:ForceUpdate()
            assert(shrine._frostawake:value(), "first nearby player wakes the shrine")
            second.Transform:SetPosition(1, 0, 1)
            first.Transform:SetPosition(15, 0, 0)
            prox:ForceUpdate()
            assert(shrine._frostawake:value(), "second player keeps shrine awake")
            second.Transform:SetPosition(15, 0, 1)
            prox:ForceUpdate()
            assert(not shrine._frostawake:value(), "last player leaving switches off")
            first:AddTag("playerghost")
            first.Transform:SetPosition(1, 0, 0)
            prox:ForceUpdate()
            assert(not shrine._frostawake:value(), "ghosts do not wake the shrine")
            first:RemoveTag("playerghost")
            prox:ForceUpdate()
            assert(shrine._frostawake:value(), "living player wakes it again")

            local stone = assert(SpawnPrefab("heatrock"))
            stone.components.temperature:SetTemperature(50)
            assert(shrine.components.trader:AcceptGift(first, stone), "temperature exchange accepted")
            assert(stone.components.temperature:GetCurrent() == stone.components.temperature.mintemp)
            assert(shrine._frostnextuse ~= nil, "successful use triggers new feedback")
            assert(shrine.AnimState:IsCurrentAnimation("jiggle"))
            local nextuse = shrine._frostnextuse
            local invalid = assert(SpawnPrefab("twigs"))
            assert(not shrine.components.trader:AcceptGift(first, invalid), "invalid item still refused")
            assert(shrine._frostnextuse == nextuse, "refusal does not trigger successful use pulse")
            shrine.components.workable:WorkedBy(first, 1)
            assert(shrine.components.workable:GetWorkLeft() == 3)
            shrine:PushEvent("onbuilt", {builder = first})
            assert(shrine.AnimState:GetCurrentAnimationLength() > .8)
            first:Remove()
            prox:ForceUpdate()
            assert(not shrine._frostawake:value(), "disconnect/removal cannot leave shrine awake")

            second.Transform:SetPosition(1, 0, 0)
            prox:ForceUpdate()
            assert(shrine._frostawake:value())
            shrine:Remove(); second:Remove(); stone:Remove(); invalid:Remove()
            print("[FROST_ART_PROBE] PASS: native proximity/multiplayer/ghost/disconnect; temperature trade; refusal; hammer; build; active removal")
            TheWorld:DoStaticTaskInTime(1, function() c_shutdown(false) end)
        end)
    end)
end)
