local G = GLOBAL
G.setmetatable(env, {__index = function(_, key) return G.rawget(G, key) end})

local mode = GetModConfigData("probe_mode")
local function near(actual, expected, label)
    assert(type(actual) == "number" and math.abs(actual - expected) < 1e-7,
        string.format("%s: expected %.9f, got %s", label, expected, tostring(actual)))
end

local function run(world)
    assert(TheNet:GetServerName() == "ShadowWorld UM temperature regression")
    local x, y, z = world.components.playerspawner:GetAnySpawnPoint()
    local players = {}
    local function spawn()
        local player = SpawnPrefab("wilson")
        player.Transform:SetPosition(x, y, z)
        player.entity:SetCanSleep(false)
        player:StopUpdatingComponent(player.components.temperature)
        player.um_temp_healthdelta = 20
        table.insert(players, player)
        return player, player.components.health
    end
    local function damage(health, amount, cause)
        return health:DoDelta(-amount, true, cause or "cold", true, nil, true)
    end
    local function done(label)
        print("[UM TEMP] PASS " .. label)
    end
    TUNING.DSTU.ANNOUNCE_BASESTATUS = false
    local charcoal = SpawnPrefab("charcoal")
    local _, horse = pcall(SpawnPrefab, "the_real_charles_t_horse")
    assert(type(horse) == "table" and horse.components.equippable ~= nil)
    local _, ordinary = spawn()
    damage(ordinary, 1)
    if mode == "off" or mode == "um-disabled" then
        near(ordinary.penalty, mode == "off" and 1/150 or 0, "unwrapped UM behavior")
        if mode == "off" then assert(charcoal.open_task2hm == nil, "rat score patch is disabled") end
        if mode == "um-disabled" then near(horse.components.equippable.walkspeedmult, 1.25, "other patches still enabled") end
        print("[UM TEMP] COMPLETE " .. mode)
        TheSim:Quit()
        return
    end
    near(horse.components.equippable.walkspeedmult, 1.25, "old second tier")
    assert(charcoal:HasTag("NORATCHECK"))
    near(ordinary.penalty, 0, "first penalty is pending")
    done("default/legacy switch applies former tiers")

    local grace, gh = spawn()
    grace.um_temp_healthdelta = 0
    damage(gh, 1)
    near(gh:GetMaxWithPenalty(), 150, "grace remains native")
    assert(grace.um_temp_healthdelta > 0)
    local resistance, rh = spawn()
    resistance:AddTag("weerclops")
    damage(rh, 1)
    near(rh.currenthealth, 149, "weerclops current health")
    near(rh:GetMaxWithPenalty(), 150, "weerclops cap")
    resistance:RemoveTag("weerclops")
    damage(rh, 1)
    resistance:AddTag("coldresistant")
    damage(rh, 1)
    resistance:AddTag("heatresistant")
    damage(rh, 1, "hot")
    near(rh:GetMaxWithPenalty(), 149, "accepted tick survives resistance gained mid-window")
    resistance:RemoveTag("heatresistant")
    damage(rh, 2, "hot")
    near(rh:GetMaxWithPenalty(), 147, "mixed hot and cold retain both amounts")
    done("grace and three native resistance tags")

    local _, healed = spawn()
    damage(healed, 3)
    near(healed.currenthealth, 147, "temperature damage remains immediate")
    near(healed:GetMaxWithPenalty(), 147, "gameplay getter sees pending cap")
    healed:DoDelta(100, false, "test_heal", true)
    near(healed.currenthealth, 147, "healing clamps immediately")
    near(healed.penalty, .02, "healing settles pending")
    local _, direct = spawn()
    damage(direct, 3, "hot")
    direct:SetVal(150, "test_heal")
    near(direct.currenthealth, 147, "direct SetVal healing")
    damage(direct, 1)
    direct:SetPercent(1)
    near(direct.currenthealth, 146, "direct SetPercent healing")
    damage(direct, 1)
    direct:SetMaxHealth(300)
    near(direct.currenthealth, 290, "change of max health uses earned fractional penalty")
    damage(direct, 2)
    direct:SetCurrentHealth(200)
    near(direct.penalty, 6/150, "direct current health setter settles")
    done("healing via DoDelta, SetVal, SetPercent and direct setters")

    local _, capped = spawn()
    capped:SetPenalty(.749)
    capped:SetPercent(1)
    damage(capped, 1)
    near(capped:GetMaxWithPenalty(), 37.5, "cap threshold crossed")
    capped:DeltaPenalty(-.01)
    near(capped.penalty, .74, "clamp before external restoration")
    damage(capped, 1)
    capped:DeltaPenalty(.1)
    near(capped.penalty, .75, "external penalty uses pending first")
    damage(capped, 1)
    capped:DeltaPenalty(-.02)
    near(capped.penalty, .73, "no backlog at ceiling")
    damage(capped, 1)
    capped:SetPenalty(.02)
    near(capped.penalty, .02, "absolute penalty setter wins")
    done("relative, absolute and capped penalty ordering")

    local hungry, hh = spawn()
    damage(hh, 1)
    hungry.um_temp_hungerdelta = 2
    damage(hh, 2, "hunger")
    near(hh.penalty, .02, "hunger is still immediate")
    damage(hh, 1)
    damage(hh, 2, "combat")
    near(hh.penalty, 4/150, "ordinary damage cannot gain temperature penalty")
    local _, disabled = spawn()
    disabled.disable_penalty = true
    damage(disabled, 1)
    near(disabled:GetMaxWithPenalty(), 150, "penalty disabled")
    disabled.disable_penalty = false
    damage(disabled, 2)
    disabled.disable_penalty = true
    damage(disabled, 1)
    near(disabled.penalty, 2/150, "earned penalty survived later disable")
    local _, nonlethal = spawn()
    nonlethal.nonlethal_temperature = true
    nonlethal.nonlethal_pct = .01
    nonlethal:SetVal(.5, "test")
    damage(nonlethal, 1)
    near(nonlethal.currenthealth, .5, "nonlethal threshold remains native")
    near(nonlethal:GetMaxWithPenalty(), 150, "rejected damage has no penalty")
    local _, redirected = spawn()
    redirected.redirect = function() return true end
    damage(redirected, 1)
    near(redirected.currenthealth, 150, "redirected damage")
    near(redirected:GetMaxWithPenalty(), 150, "redirected damage has no penalty")
    local _, dead = spawn()
    dead:SetVal(2, "test")
    damage(dead, 1)
    damage(dead, 1)
    assert(dead:IsDead())
    near(dead.penalty, 2/150, "lethal tick and earlier pending amount")
    done("hunger, combat, disabled penalties, nonlethal and death")

    local _, loadedInPlace = spawn()
    damage(loadedInPlace, 2)
    loadedInPlace:OnLoad({health = 100, penalty = .1})
    near(loadedInPlace.penalty, .1, "in-place restoration")
    local transferSource, th = spawn()
    local transferTarget = spawn()
    damage(th, 2)
    th:TransferComponent(transferTarget)
    near(th.penalty, 2/150, "component transfer settles source")
    local reroll, rerollHealth = spawn()
    damage(rerollHealth, 2)
    reroll:SaveForReroll()
    near(rerollHealth.penalty, 2/150, "reroll reads settled penalty")
    local signal, sh = spawn()
    signal:PushEvent("healthdelta", {cause = "cold", amount = -1})
    near(sh.currenthealth, 149, "immediate clamp when an event must lower current health")
    near(sh.penalty, 1/150, "immediate clamp commits")
    local nested, nh = spawn()
    local ran
    nested:ListenForEvent("healthdelta", function(_, data)
        if data.amount == 0 and not ran then
            ran = true
            nh:DeltaPenalty(.01)
        end
    end)
    nested:PushEvent("healthdelta", {cause = "cold", amount = -1})
    near(nh.penalty, 1/150 + .01, "nested unrelated penalty is immediate")

    local saving, saved = spawn()
    local earlierRecord = saving:GetSaveRecord()
    damage(saved, 2)
    local record = saving:GetSaveRecord()
    near(record.data.health.penalty, 2/150, "pending written into native record")
    near(saving:GetSaveRecord().data.health.penalty, 2/150, "repeated save does not double")
    near(saved.penalty, 0, "save does not modify live player")
    local restored = SpawnSaveRecord(record)
    table.insert(players, restored)
    restored:StopUpdatingComponent(restored.components.temperature)
    near(restored.components.health.penalty, 2/150, "native save record restores accrued amount")
    near(restored.components.health.currenthealth, 148, "native record restores current health")
    local rolledBack = SpawnSaveRecord(earlierRecord)
    rolledBack:StopUpdatingComponent(rolledBack.components.temperature)
    near(rolledBack.components.health.penalty, 0, "earlier snapshot has no future penalty")
    near(rolledBack.components.health.currenthealth, 150, "earlier snapshot has no future damage")

    local migrant, mh = spawn()
    migrant.userid = "KU_UM_TEMP_TEST"
    damage(mh, 3, "hot")
    migrant.migration = {portalid = 1, worldid = "2"}
    SerializeUserSession(migrant)
    done("native player save and repeated snapshots")
    local migrationVerified
    world:DoTaskInTime(.1, function()
        local file = TheNet:GetUserSessionFile(world.meta.session_identifier, migrant.userid)
        assert(file ~= nil, "missing serialized user session")
        TheNet:DeserializeUserSession(file, function(ok, data)
            assert(ok, "could not read serialized user session")
            local unpacked = assert(loadstring(data))()
            near(unpacked.data.health.penalty, .02, "migration payload preserves pending")
            near(unpacked.data.health.health, 147, "migration payload current health")
            local destination = SpawnSaveRecord(unpacked)
            table.insert(players, destination)
            destination:StopUpdatingComponent(destination.components.temperature)
            near(destination.components.health.penalty, .02, "migration session restores penalty")
            migrationVerified = true
            done("native user-session serialization and restore")
        end)
    end)

    local _, timed = spawn()
    damage(timed, 1)
    world:DoTaskInTime(.1, function() damage(timed, 2, "hot") end)
    world:DoTaskInTime(.2, function()
        near(timed.penalty, 0, "two ticks share one settlement")
        near(timed:GetMaxWithPenalty(), 147, "pending cap before deadline")
    end)
    world:DoTaskInTime(.3, function()
        near(timed.penalty, 3/150, "first deadline includes both ticks")
        damage(timed, 1)
    end)
    local removed, removedHealth = spawn()
    damage(removedHealth, 2)
    removed:Remove()

    world:DoTaskInTime(.65, function()
        assert(migrationVerified, "user-session read did not complete")
        assert(TUNING.DSTU.ANNOUNCE_BASESTATUS, "former third tier announced rat score")
        near(ordinary.penalty, 1/150, "timer settles one tick")
        near(rh.penalty, .02, "resistance change and mixed temperatures settle once")
        near(saved.penalty, 2/150, "source settlement still runs after save")
        near(restored.components.health.penalty, 2/150, "restored player does not charge twice")
        near(loadedInPlace.penalty, .1, "in-place restore cancels stale task")
        near(healed.penalty, .02, "healing did not leave a duplicate settlement")
        near(capped.penalty, .02, "external penalty did not leave a duplicate settlement")
        near(timed.penalty, 4/150, "next window commits independently")
        done("timer tail, cancellation and no double charge")
        print("[UM TEMP] COMPLETE " .. mode)
        TheSim:Quit()
    end)
end

AddPrefabPostInit("world", function(world)
    if world.ismastersim then world:DoTaskInTime(3, run) end
end)
