"""Build weighted hand symbols from Klei's BILD v6 geometry, retaining encrypted skin textures.
Format reference: the installed official Mod Tools tools/scripts/buildanimation.py.
No texture decryption or new skin IDs: each build remains restricted to the original skin.
"""
from pathlib import Path
from zipfile import ZipFile,ZIP_DEFLATED,ZipInfo
from io import BytesIO
import struct,re,shutil,json
ROOT=Path(__file__).resolve().parents[2]
GAME=Path("D:/SteamLibrary/steamapps/common/Don't Starve Together/data")
SCALES=[1,1.17,1.31,1.44,1.55,1.65,1.74,1.82,1.9,1.97,2.04,2.11,2.23,2.29,2.35,2.4,2.46,2.5]
def name(scale):return 'swap_ham_bat_'+format(scale,'.2f').replace('.','_')
def hashname(s):
 h=0
 for c in s.lower().encode():h=(h*65599+c)&0xffffffff
 return h
class Reader:
 def __init__(self,b):self.b=b;self.i=0
 def take(self,n):x=self.b[self.i:self.i+n];self.i+=n;return x
 def read(self,fmt):n=struct.calcsize('<'+fmt);return struct.unpack('<'+fmt,self.take(n))
 def string(self):return self.take(self.read('I')[0]).decode()
def string(s):b=s.encode();return struct.pack('<I',len(b))+b
def readbuild(b):
 r=Reader(b);assert r.take(4)==b'BILD'and r.read('I')[0]==6
 ns,nf=r.read('II');build=r.string();materials=[r.string()for _ in range(r.read('I')[0])]
 symbols=[]
 for _ in range(ns):
  h,n=r.read('II');frames=[r.read('IIffffII')for _ in range(n)];symbols.append((h,frames))
 vertices=[r.read('ffffff')for _ in range(r.read('I')[0])]
 strings={}
 for _ in range(r.read('I')[0]):h=r.read('I')[0];strings[h]=r.string()
 assert r.i==len(b)and nf==sum(len(f)for _,f in symbols)
 return build,materials,symbols,vertices,strings

def weighttransforms():
 # Reproduce the existing hand art, including its grip/pivot correction.
 with ZipFile(GAME/'anim/swap_ham_bat.zip')as z:
  _,_,symbols,_,_=readbuild(z.read('build.bin'))
 x0,y0,w0,h0=next(f for h,f in symbols if h==hashname('swap_ham_bat'))[0][2:6]
 transforms={}
 for scale in SCALES:
  with ZipFile(ROOT/('content/anim/'+name(scale)+'.zip'))as z:
   _,_,symbols,_,_=readbuild(z.read('build.bin'))
  x,y,w,h=symbols[0][1][0][2:6]
  sx,sy=w/w0,h/h0
  transforms[scale]=(sx,sy,x-x0*sx,y-y0*sy)
 return transforms

def buildskin(raw,newbuild,transforms):
 _,materials,symbols,vertices,strings=readbuild(raw)
 source=next(frames for h,frames in symbols if strings[h]=='swap_ham_bat')
 outsyms=[];outverts=[];names={}
 for scale in SCALES:
  symbol=name(scale);h=hashname(symbol);names[h]=symbol;frames=[]
  sx,sy,dx,dy=transforms[scale]
  for frame,duration,x,y,w,height,start,count in source:
   pos=len(outverts)
   outverts.extend((vx*sx+dx,vy*sy+dy,vz,u,v,page)for vx,vy,vz,u,v,page in vertices[start:start+count])
   frames.append((frame,duration,x*sx+dx,y*sy+dy,w*sx,height*sy,pos,count))
  outsyms.append((h,frames))
 outsyms.sort()
 b=b'BILD'+struct.pack('<III',6,len(outsyms),sum(len(f)for _,f in outsyms))+string(newbuild)
 b+=struct.pack('<I',len(materials))+b''.join(string(s)for s in materials)
 for h,frames in outsyms:
  b+=struct.pack('<II',h,len(frames))+b''.join(struct.pack('<IIffffII',*f)for f in frames)
 b+=struct.pack('<I',len(outverts))+b''.join(struct.pack('<ffffff',*v)for v in outverts)
 b+=struct.pack('<I',len(names))+b''.join(struct.pack('<I',h)+string(s)for h,s in sorted(names.items()))
 readbuild(b)
 return b

def main():
 with ZipFile(GAME/'databundles/scripts.zip')as z:
  catalog=z.read('scripts/prefabskins.lua').decode('utf-8-sig');skins=re.findall(r'"([^"]+)"',re.search(r'\bhambat\s*=\s*\{([^}]+)\}',catalog).group(1))
 target=ROOT/'content/anim/dynamic';target.mkdir(exist_ok=True)
 metadata={}
 transforms=weighttransforms()
 with ZipFile(GAME/'databundles/anim_dynamic.zip')as z:
  for skin in skins:
   build=skin+'_weighted2hm'
   with ZipFile(BytesIO(z.read('anim/dynamic/'+skin+'.zip')))as source:raw=source.read('build.bin')
   with ZipFile(target/(build+'.zip'),'w',ZIP_DEFLATED)as output:
    entry=ZipInfo('build.bin',(1980,1,1,0,0,0));entry.compress_type=ZIP_DEFLATED;output.writestr(entry,buildskin(raw,build,transforms))
   shutil.copyfile(GAME/('anim/dynamic/'+skin+'.dyn'),target/(build+'.dyn'))
   metadata[skin]=build
 path=ROOT/'content/scripts/hambatweightedskins2hm.lua'
 path.write_bytes(('-- Generated by development/tools/build_hambat_skin_weights.py.\r\nreturn {\r\n'+''.join('    ["'+skin+'"] = "'+build+'",\r\n'for skin,build in metadata.items())+'}\r\n').encode())
 print(json.dumps(metadata,indent=2))
if __name__=='__main__':main()
